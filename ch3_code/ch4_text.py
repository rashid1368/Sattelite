_FA = str.maketrans("0123456789.", "۰۱۲۳۴۵۶۷۸۹٫")


def _ale_days(tag):
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "logs", "t8_ale1.jsonl")
    if not os.path.exists(p):
        return "—"
    for line in open(p, encoding="utf8"):
        if line.strip():
            r = json.loads(line)
            if r.get("tag") == tag and r.get("t400_days") is not None:
                return ("%.1f" % r["t400_days"]).translate(_FA)
    return "—"


