# typo fix in chapter 4 text
for p in d.element.body.iter(W + "p"):
    for t in p.iter(W + "t"):
        if t.text and "نایکنواست" in t.text:
            t.text = t.text.replace("نایکنواست", "نایکنوایی")

def add_heading_and_body(anchor, heading, texts, H, B):
    prev = clone_par_after(anchor, H, heading)
    for t in texts:
        prev = clone_par_after(prev, B, t)
    return prev

