n = 0
for old, new in GLOBAL:
    for k in kids[C5[0]:C5[1]]:
        for p in k.iter(W + "p"):
            while old in ptext(p):
                if replace_in_text_nodes(p, old, new):
                    n += 1
                else:
                    set_par_text(p, ptext(p).replace(old, new)); n += 1
                    break
log.append("global replacements in ch5: %d" % n)

def sentence(old, new):
    p = find_text(old)
    if not replace_in_text_nodes(p, old, new):
        set_par_text(p, ptext(p).replace(old, new))
    log.append("sentence: " + old[:35])

def rewrite(prefix, new_text):
    set_par_text(find_one(prefix), new_text)
    log.append("rewrite: " + prefix[:35])

