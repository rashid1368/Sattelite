import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import docx
from docx_util import W, ptext, clone_par_after

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PATH = os.path.join(ROOT, "_build", "thesis_v10_draft.docx")
d = docx.Document(PATH)
kids = list(d.element.body.iterchildren())

def find(prefix):
    hits = [k for k in kids if ptext(k).strip().startswith(prefix)]
    assert len(hits) == 1, (prefix, len(hits))
    return hits[0]

T_BODY = find("پیامد طراحی این یافته")
T_H3 = [k for k in kids if ptext(k).strip().startswith("۵-۲-۱ فرضیه‌ی اول")][-1]

def add_after(anchor_prefix, texts, template=T_BODY):
    prev = find(anchor_prefix)
    for t in texts:
        prev = clone_par_after(prev, template, t)

def add_heading_and_body(anchor_prefix, heading, texts):
    prev = clone_par_after(find(anchor_prefix), T_H3, heading)
    for t in texts:
        prev = clone_par_after(prev, T_BODY, t)

